-- 0004: third normal form (3NF), as the real sales tables, owned by companies.
--
-- The rule: no column depends on another non-key column. Each fact is stored
-- once, in the table about the thing it describes.
--
-- What breaks it in staging.orders_2nf (key: order_number): customer_email
-- and customer_city depend on customer_name, which isn't the key. They're
-- facts about the customer, copied onto each of the customer's orders, so a
-- move or a new email has to be retyped on every order (that's how Corner
-- Market ended up in two cities).
--
-- The fix: a customers table, and orders point at it. Categories get their
-- own table too: strictly, a category name alone doesn't break 3NF, but a
-- category is something Stockroom manages (rename it once, keep a fixed
-- list), and a foreign key stops a product being filed under a misspelling.
--
-- Choices forced by the split (the copies disagreed):
--   - Email: lower-cased, so "Buying@BluebonnetGrocers.example" and
--     "buying@bluebonnetgrocers.example" are one address; a CHECK keeps it so.
--   - City: the city on the customer's most recent order (Corner Market:
--     Round Rock, where it moved in June). Old orders don't record a city at
--     all now: an order is linked to the customer, wherever they are.
--
-- A copy on purpose: order_items.unit_price repeats the product's price, which
-- 3NF would normally remove. It stays, because it's a different fact: the
-- price this line was sold at. Olive Oil 1L lines from before June keep 11.99
-- although the list price is now 12.99; recomputing old orders from today's
-- price would change revenue that was already earned and invoiced.
--
-- Every table is owned by a company: org_id is the organization ID from the
-- auth database (D1, step 04), the company the signed-in user chose. It's
-- part of every primary key and every foreign key, so a row can only point at
-- rows of its own company: an order line of company A can't name company B's
-- order or product, because the pair (org_id, id) must exist on the other side.
-- (Row-level security on org_id arrives in step 06.)
--
-- The sample data goes into a demo company, org_id 'demo'. It isn't an
-- organization in D1, so nobody can sign into it. `npm run db:seed` copies it
-- into a real company (yours).

CREATE TABLE categories (
  org_id      text    NOT NULL,
  category_id integer GENERATED BY DEFAULT AS IDENTITY,
  name        text    NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 50),
  PRIMARY KEY (org_id, category_id),
  UNIQUE (org_id, name)
);

CREATE TABLE products (
  org_id      text          NOT NULL,
  product_id  integer       GENERATED BY DEFAULT AS IDENTITY,
  name        text          NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
  category_id integer       NOT NULL,
  list_price  numeric(10,2) NOT NULL CHECK (list_price >= 0),
  PRIMARY KEY (org_id, product_id),
  UNIQUE (org_id, name),
  FOREIGN KEY (org_id, category_id) REFERENCES categories (org_id, category_id)
);

CREATE TABLE customers (
  org_id      text    NOT NULL,
  customer_id integer GENERATED BY DEFAULT AS IDENTITY,
  name        text    NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
  email       text    NOT NULL CHECK (email = lower(email) AND email LIKE '%_@_%'),
  city        text    NOT NULL CHECK (length(trim(city)) BETWEEN 1 AND 100),
  PRIMARY KEY (org_id, customer_id),
  UNIQUE (org_id, email)
);

CREATE TABLE orders (
  org_id       text    NOT NULL,
  order_id     integer GENERATED BY DEFAULT AS IDENTITY,
  order_number text    NOT NULL,
  customer_id  integer NOT NULL,
  order_date   date    NOT NULL,
  PRIMARY KEY (org_id, order_id),
  UNIQUE (org_id, order_number),
  FOREIGN KEY (org_id, customer_id) REFERENCES customers (org_id, customer_id)
);

CREATE TABLE order_items (
  org_id     text          NOT NULL,
  order_id   integer       NOT NULL,
  product_id integer       NOT NULL,
  quantity   integer       NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
  PRIMARY KEY (org_id, order_id, product_id),
  -- Deleting an order deletes its lines (they mean nothing without it).
  FOREIGN KEY (org_id, order_id) REFERENCES orders (org_id, order_id) ON DELETE CASCADE,
  -- A product that has been sold can't be deleted: the sale must still say what was sold.
  FOREIGN KEY (org_id, product_id) REFERENCES products (org_id, product_id)
);

-- Postgres indexes primary keys and UNIQUE columns itself, but not the
-- referencing side of a foreign key. These serve the joins and date filters
-- the business questions use.
CREATE INDEX orders_customer_idx ON orders (org_id, customer_id);
CREATE INDEX orders_date_idx ON orders (org_id, order_date);
CREATE INDEX order_items_product_idx ON order_items (org_id, product_id);
CREATE INDEX products_category_idx ON products (org_id, category_id);

COMMENT ON COLUMN order_items.unit_price IS 'The price this line was sold at: a copy of the list price on purpose, so later price changes never alter past sales.';

-- The sample data, into the demo company, from the 2NF tables.
INSERT INTO categories (org_id, name)
SELECT DISTINCT 'demo', category FROM staging.products_2nf ORDER BY 2;

INSERT INTO products (org_id, name, category_id, list_price)
SELECT 'demo', p.product_name, c.category_id, p.list_price
FROM staging.products_2nf AS p
JOIN categories AS c ON c.org_id = 'demo' AND c.name = p.category
ORDER BY p.product_name;

-- One row per customer: the name identified them in the spreadsheet. DISTINCT
-- ON keeps the first row per name in the ORDER BY, i.e. the latest order.
INSERT INTO customers (org_id, name, email, city)
SELECT 'demo', customer_name, lower(customer_email), customer_city
FROM (
  SELECT DISTINCT ON (customer_name) customer_name, customer_email, customer_city
  FROM staging.orders_2nf
  ORDER BY customer_name, order_date DESC, order_number DESC
) AS latest
ORDER BY customer_name;

INSERT INTO orders (org_id, order_number, customer_id, order_date)
SELECT 'demo', o.order_number, c.customer_id, o.order_date
FROM staging.orders_2nf AS o
JOIN customers AS c ON c.org_id = 'demo' AND c.name = o.customer_name
ORDER BY o.order_number;

INSERT INTO order_items (org_id, order_id, product_id, quantity, unit_price)
SELECT 'demo', o.order_id, p.product_id, l.quantity, l.unit_price
FROM staging.order_lines_2nf AS l
JOIN orders   AS o ON o.org_id = 'demo' AND o.order_number = l.order_number
JOIN products AS p ON p.org_id = 'demo' AND p.name = l.product_name;
